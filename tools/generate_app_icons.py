"""
Regenerates the PWA/home-screen icons (assets/apple-touch-icon.png,
assets/icon-192.png, assets/icon-512.png) from assets/logo.png. Only needs
re-running if you change the logo -- the generated files are committed to
the repo since, unlike the desktop build's assets/app.ico (regenerated by
build_desktop.py on every build), they're read directly by the live app
(index.html, manifest.json) rather than produced fresh each time.

Needs Pillow: python -m pip install pillow
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent


def main():
    logo = ROOT / "assets" / "logo.png"
    img = Image.open(logo).convert("RGBA")
    # iOS renders transparency as solid black behind a home-screen icon, so
    # flatten onto the app's own dark background instead of leaving it
    # transparent.
    bg = Image.new("RGBA", img.size, (20, 22, 27, 255))
    composited = Image.alpha_composite(bg, img)

    composited.resize((180, 180), Image.LANCZOS).convert("RGB").save(ROOT / "assets" / "apple-touch-icon.png")
    composited.resize((192, 192), Image.LANCZOS).save(ROOT / "assets" / "icon-192.png")
    composited.resize((512, 512), Image.LANCZOS).save(ROOT / "assets" / "icon-512.png")
    print("Wrote assets/apple-touch-icon.png, icon-192.png, icon-512.png")


if __name__ == "__main__":
    main()
